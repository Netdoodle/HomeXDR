func TestCompare(t *testing.T) {
	for _, tc := range []struct {
		kind, a, b string
		want       int
	}{
		{"deb", "1.0~rc1", "1.0", -1},
		{"apk", "1.2.3-r4", "1.2.3-r3", 1},
		{"rpm", "1.0-1.el9", "1.0-1.el9", 0},
	} {
		got, ok := Compare(tc.kind, tc.a, tc.b)
		if !ok || got != tc.want {
			t.Errorf("Compare(%q, %q, %q) = %d, %v", tc.kind, tc.a, tc.b, got, ok)
		}
	}
	if _, ok := Compare("pacman", "1", "2"); ok {
		t.Error("unknown kind should not be ok")
	}
}
