package version

import "testing"

type vec struct {
	a, b string
	want int
}

func run(t *testing.T, name string, fn func(a, b string) int, vs []vec) {
	t.Helper()
	for _, v := range vs {
		if got := fn(v.a, v.b); got != v.want {
			t.Errorf("%s(%q, %q) = %d, want %d", name, v.a, v.b, got, v.want)
		}
		if got := fn(v.b, v.a); got != -v.want {
			t.Errorf("%s(%q, %q) = %d, want %d (reversed)", name, v.b, v.a, got, -v.want)
		}
	}
}

